-- نکته: اولین مدیر را با Edge Function بسازید؛ service_role هرگز در فرانت قرار نمی گیرد.

-- امنیت مهم: کاربری که فقط اجازه تغییر قیمت/موجودی دارد نباید بتواند ستون های دیگر را دستکاری کند.
create or replace function public.enforce_inventory_field_permissions()
returns trigger language plpgsql security definer set search_path=public
as $$
begin
  if public.has_permission('edit_item') then return new; end if;
  if not public.has_permission('change_price') and new.price is distinct from old.price then
    raise exception 'PERMISSION_DENIED_PRICE';
  end if;
  if not public.has_permission('change_quantity') and new.quantity is distinct from old.quantity then
    raise exception 'PERMISSION_DENIED_QUANTITY';
  end if;
  if new.category is distinct from old.category or new.brand is distinct from old.brand or new.model is distinct from old.model
     or new.unit is distinct from old.unit or new.owner_type is distinct from old.owner_type
     or new.item_condition is distinct from old.item_condition or new.warranty is distinct from old.warranty
     or new.description is distinct from old.description then
    raise exception 'PERMISSION_DENIED_FIELDS';
  end if;
  return new;
end;
$$;

drop trigger if exists inventory_permission_trigger on public.inventory;
create trigger inventory_permission_trigger before update on public.inventory for each row execute function public.enforce_inventory_field_permissions();
